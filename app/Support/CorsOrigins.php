<?php

namespace App\Support;

use InvalidArgumentException;

/**
 * Browser origins allowed to call this engine.
 *
 * Laravel's CORS middleware only sees PHP routes. Room panoramas are
 * static files under /storage/uploads/rooms and are served by nginx, so
 * `php artisan storage:cors-map` turns this same list into an nginx map.
 * FRONTEND_URL stays a single origin because Google OAuth redirects there.
 * Extra origins can be added with CORS_ALLOWED_ORIGINS (comma-separated).
 * A wildcard is never emitted.
 */
class CorsOrigins
{
    /**
     * SPAs that load panoramas from this engine. FRONTEND_URL can only
     * name one of them.
     *
     * @return list<string>
     */
    public static function firstParty(): array
    {
        return [
            'https://greyon.site',
            'https://www.greyon.site',
            'https://dev-greyon.mxlab.site',
        ];
    }

    /**
     * @return list<string>
     */
    public static function patterns(): array
    {
        return [
            '#^http://localhost:\d+$#',
            '#^http://127\.0\.0\.1:\d+$#',
        ];
    }

    /**
     * @return list<string>
     */
    public static function allowed(): array
    {
        return self::normalize(array_merge(
            self::split(env('FRONTEND_URL')),
            self::split(env('CORS_ALLOWED_ORIGINS')),
            self::firstParty(),
            [
                'http://localhost:9000',
                'http://127.0.0.1:9000',
                'http://localhost:9400',
                'http://127.0.0.1:9400',
            ],
        ));
    }

    public static function allows(string $origin): bool
    {
        if (in_array($origin, self::allowed(), true)) {
            return true;
        }

        foreach (self::patterns() as $pattern) {
            if (preg_match($pattern, $origin) === 1) {
                return true;
            }
        }

        return false;
    }

    /**
     * Drop blanks, trailing slashes, wildcards, and values that cannot
     * be placed safely in an nginx map.
     *
     * @param  list<mixed>  $origins
     * @return list<string>
     */
    public static function normalize(array $origins): array
    {
        $out = [];

        foreach ($origins as $origin) {
            if (! is_string($origin)) {
                continue;
            }

            $origin = rtrim(trim($origin), '/');
            if (! self::isValidOrigin($origin)) {
                continue;
            }

            $out[$origin] = $origin;
        }

        return array_values($out);
    }

    /**
     * nginx `map` for $storage_cors_origin and $storage_cors_credentials.
     * Included from the Nixpacks nginx template. Never contains `*`.
     *
     * @param  list<mixed>  $origins
     * @param  list<mixed>  $patterns
     */
    public static function nginxMap(array $origins, array $patterns): string
    {
        $lines = [
            '# Generated by `php artisan storage:cors-map` from config/cors.php.',
            '# Static /storage files are served by nginx and skip Laravel CORS.',
            'map $http_origin $storage_cors_origin {',
            '    default "";',
        ];

        foreach (self::normalize($origins) as $origin) {
            $lines[] = '    "'.self::escapeQuoted($origin).'" $http_origin;';
        }

        foreach ($patterns as $pattern) {
            if (! is_string($pattern) || $pattern === '') {
                throw new InvalidArgumentException('CORS origin patterns must be strings.');
            }
            $lines[] = '    '.self::toNginxRegex($pattern).' $http_origin;';
        }

        $lines[] = '}';
        $lines[] = '';
        $lines[] = 'map $storage_cors_origin $storage_cors_credentials {';
        $lines[] = '    "" "";';
        $lines[] = '    default "true";';
        $lines[] = '}';
        $lines[] = '';

        $map = implode("\n", $lines);
        if (str_contains($map, '*')) {
            throw new InvalidArgumentException('Refusing to emit a wildcard CORS nginx map.');
        }

        return $map;
    }

    /**
     * @return list<string>
     */
    private static function split(mixed $value): array
    {
        if (! is_string($value) || trim($value) === '') {
            return [];
        }

        $parts = preg_split('/\s*,\s*/', trim($value)) ?: [];

        return array_values(array_filter($parts, fn (string $part) => $part !== ''));
    }

    private static function isValidOrigin(string $origin): bool
    {
        return preg_match('#\Ahttps?://[A-Za-z0-9._:-]+\z#', $origin) === 1;
    }

    private static function escapeQuoted(string $value): string
    {
        return str_replace(['\\', '"'], ['\\\\', '\\"'], $value);
    }

    private static function toNginxRegex(string $phpPattern): string
    {
        $delimiter = $phpPattern[0] ?? '';
        if ($delimiter === '' || ! preg_match('/\A(.)(.*)\1([a-zA-Z]*)\z/s', $phpPattern, $matches)) {
            throw new InvalidArgumentException("Invalid CORS origin pattern: {$phpPattern}");
        }

        $body = $matches[2];
        $flags = $matches[3];
        if ($flags !== '') {
            throw new InvalidArgumentException("Unsupported CORS origin pattern flags: {$phpPattern}");
        }
        if (preg_match('/[\s\'"{}#;*]/', $body) === 1) {
            throw new InvalidArgumentException("CORS origin pattern cannot be expressed safely in nginx: {$phpPattern}");
        }

        return '~'.$body;
    }
}
